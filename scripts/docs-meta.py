"""Regenerates playground/docs/meta.ts: one description per component/block/template and the demo section each slug lives in.
Run after adding or renaming a component: python3 -I scripts/docs-meta.py"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATALOG = (ROOT / "playground/docs/catalog.ts").read_text()


def entries(name):
    block = re.search(rf"export const {name}: \w+\[\] = (\[.*?\n\]);", CATALOG, flags=re.S).group(1)
    return json.loads(block)


def header(path):
    if not path.exists():
        return ""
    m = re.search(r"/\*\s*(.*?)\s*\*/", path.read_text(), flags=re.S)
    if not m:
        return ""
    text = " ".join(m.group(1).split())
    head, sep, rest = text.partition(": ")
    out = rest if sep and len(head) <= 48 else text
    return out[:1].upper() + out[1:]


descriptions = {}
for c in entries("COMPONENTS"):
    if c["tier"] == "Free":
        meta = ROOT / "registry" / f"{c['slug']}.json"
        descriptions[c["slug"]] = json.loads(meta.read_text()).get("description", "") if meta.exists() else ""
    else:
        descriptions[c["slug"]] = header(ROOT / "originals/ui" / f"{c['slug']}.tsx")
for b in entries("BLOCKS"):
    descriptions[b["slug"]] = header(ROOT / "originals/blocks" / f"{b['slug']}.tsx")
for t in entries("TEMPLATES"):
    descriptions[t["slug"]] = header(ROOT / "originals/templates" / f"{t['slug']}.tsx")

section_of = {}
for p in sorted((ROOT / "playground/sections").glob("*.tsx")):
    if p.name.endswith(".test.tsx"):
        continue
    for slug in re.findall(r'<Demo\b[^>]*?\bslug="([^"]+)"', p.read_text(), flags=re.S):
        section_of.setdefault(slug, p.stem)

missing = [s for s in descriptions if s not in section_of and not any(t["slug"] == s for t in entries("TEMPLATES"))]
out = "/* Generated by scripts/docs-meta.py — descriptions from file headers / registry metadata, and the demo section per slug. */\n\n"
out += "export const DESCRIPTIONS: Record<string, string> = " + json.dumps(descriptions, indent=1, ensure_ascii=False) + ";\n\n"
out += "export const SECTION_OF: Record<string, string> = " + json.dumps(section_of, indent=1) + ";\n"
(ROOT / "playground/docs/meta.ts").write_text(out)
print(f"{len(descriptions)} descriptions, {len(section_of)} demos; without a demo: {missing}")
